/**
 * Маршруты (паттерны событий) брокера сообщений notify.
 *
 * Общий контракт продюсеров (`users`, `blog`) и консьюмера (`notify`).
 * Событие называется по тому, что произошло у отправителя, а не по тому,
 * что с ним сделает получатель: так контракт не зависит от конкретного
 * консьюмера, и на одно событие могут подписаться несколько сервисов.
 */
export enum RabbitRouting {
  /** В `users` зарегистрирован новый пользователь. */
  UserRegistered = 'user.registered',
  /** В `blog` пост стал опубликованным: создан, репостнут, возвращён из черновика или отредактирован. */
  PostPublished = 'post.published',
  /** В `blog` пост перестал быть опубликованным: переведён в черновик или удалён. */
  PostUnpublished = 'post.unpublished',
}
